CLEAN = {"code": code(GO_CODE), "english": english(PARA + "\n" + PARA + "\n"), "math": math(BODY * 3), "sci": sci(SCI * 2)}


def pairs_in_clean_py():
    """(family, function) for every rule in clean.py, and the shared F1 on the code family."""
    out = {(fam, c._ID[make].split("-")[1]) for fam, rules in c._PIPELINES.items() for make in rules}
    return out | {("code", "F1")}


def test_every_function_is_tested_on_every_family_it_has_a_rule_for():
    assert {(fam, fn) for fam, fn, _, _ in SICK} == pairs_in_clean_py()
    assert set(c.RULES) == {fn for _, fn, _, _ in SICK}  # one function per disease code
    assert all(c.RULES[code_].__name__ == code_.lower() for code_ in c.RULES)


@pytest.mark.parametrize("family, fn, doc, action", SICK, ids=[f"{f}-{fn}" for f, fn, _, _ in SICK])
def test_a_function_treats_a_sick_document(family, fn, doc, action):
    if (family, fn) == ("code", "F1"):
        pytest.importorskip("tree_sitter_language_pack")  # the shared F1 reads comments and strings in code with tree-sitter
    a, new = c.RULES[fn](doc)
    assert a == action
    assert new == doc["text"] if action in ("drop", "keep") else new != doc["text"]


@pytest.mark.parametrize("family", CLEAN)
@pytest.mark.parametrize("fn", list(c.RULES))
def test_a_function_keeps_a_clean_document(family, fn):
    doc = CLEAN[family]
    assert c.RULES[fn](doc) == ("keep", doc["text"])


@pytest.mark.parametrize("family", CLEAN)
def test_clean_keeps_a_clean_document(family):
    assert c.clean(CLEAN[family]) == ("keep", CLEAN[family]["text"])
